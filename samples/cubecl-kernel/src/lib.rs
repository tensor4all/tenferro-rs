//! Source-blind downstream-style fixture for the CubeCL external-kernel seam
//! (issue #1597).
//!
//! This crate deliberately looks like a downstream kernel provider: it depends
//! on the published crates.io `t4a-cubecl = =0.11.0` package line and on
//! `tenferro-gpu`, then compiles and runs a real `#[cube(launch_unchecked)]`
//! kernel exclusively through the public `cuda::cubecl::Session` API. It must
//! never touch the hidden `cuda::interop` bridge.
//!
//! The fixture proves three properties:
//!
//! 1. A single `t4a-cubecl` instance across the dependency graph
//!    (`cargo tree -d`, enforced by the pre-PR gate): the launcher generated by
//!    this crate's `t4a-cubecl` takes the framework `Client` and `BufferArg`
//!    that `tenferro-gpu`'s session hands it, so two CubeCL copies in one graph
//!    would not type-check.
//! 2. The public seam supports a full upload → launch → sync → download →
//!    assert flow with no raw context handling, no `u64` stream, and no
//!    `set_current_cuda_context` in caller code, including an output allocated
//!    through `Session::alloc_output`.
//! 3. The compiled kernel is reused across `with_cubecl` scopes without any
//!    downstream cache (`run_kernel_cache_check` prints the host cost of each
//!    scope as the evidence).

pub mod kernel;
pub mod run;

pub use run::{run_kernel_cache_check, run_scale_check, run_typing_rules_check};
